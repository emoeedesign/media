def _card_for(record: dict, thumb_rel: str | None) -> str:
    rtype = record.get("type", "photo")
    sellable = bool(record.get("sellable"))

    if rtype == "photo" and thumb_rel:
        thumb = f'<img class="thumb" src="{thumb_rel}" alt="{record["filename"]}" loading="lazy" />'
    elif rtype == "video":
        thumb = '<div class="thumb-video">&#9654;</div>'
    else:
        thumb = '<div class="thumb-video">?</div>'

    if rtype == "photo":
        mp = record.get("megapixels")
        meta_text = f"{record.get('width')}×{record.get('height')} | {mp}MP | {record.get('size_mb')} MB"
    else:
        dur = record.get("duration_sec")
        meta_text = f"{record.get('width')}×{record.get('height')} | {dur}s | {record.get('size_mb')} MB"

    return _CARD_TEMPLATE.format(
        type=rtype,
        sellable=str(sellable).lower(),
        thumb=thumb,
        filename=record["filename"],
        type_label="写真" if rtype == "photo" else "動画",
        sellable_cls="sellable" if sellable else "small",
        sellable_label="販売可能" if sellable else "解像度不足",
        meta_text=meta_text,
    )


def generate_portfolio(
    scan_records: list[dict],
    output_dir: str | Path,
    title: str = "My Media Portfolio",
    platforms: list[dict] | None = None,
    thumb_dir: str | Path | None = None,
) -> Path:
    """
    スキャン結果から HTML ポートフォリオを生成する。

    Args:
        scan_records: scanner.scan_to_json() の結果リスト
        output_dir:   HTML の出力先ディレクトリ
        title:        ページタイトル
        platforms:    metadata.MAJOR_STOCK_SITES に準じたリスト
        thumb_dir:    サムネイル画像が格納されているディレクトリ

    Returns:
        生成した index.html のパス
    """
    from media_monetize.metadata import MAJOR_STOCK_SITES
    if platforms is None:
        platforms = MAJOR_STOCK_SITES

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # サムネイルをコピー
    thumb_lookup: dict[str, str] = {}
    if thumb_dir:
        thumb_dir = Path(thumb_dir)
        thumbs_out = output_dir / "thumbs"
        thumbs_out.mkdir(exist_ok=True)
        for img in thumb_dir.glob("*.jpg"):
            shutil.copy2(img, thumbs_out / img.name)
            # ファイル名から stem を取り出してマッピング
            # "photo_thumbnail.jpg" -> stem "photo"
            stem = img.stem.replace("_thumbnail", "")
            thumb_lookup[stem] = f"thumbs/{img.name}"

    cards_html = "\n".join(
        _card_for(r, thumb_lookup.get(Path(r["path"]).stem))
        for r in scan_records
    )

    platform_cards_html = "\n".join(
        _PLATFORM_CARD_TEMPLATE.format(**p)
        for p in platforms
    )

    photos = [r for r in scan_records if r.get("type") == "photo"]
    videos = [r for r in scan_records if r.get("type") == "video"]
    total_bytes = sum(r.get("size_bytes", 0) for r in scan_records)

    html = _HTML_TEMPLATE.format(
        title=title,
        generated_at=datetime.now().strftime("%Y-%m-%d %H:%M"),
        total=len(scan_records),
        sellable_photos=sum(1 for r in photos if r.get("sellable")),
        sellable_videos=sum(1 for r in videos if r.get("sellable")),
        total_gb=round(total_bytes / 1_073_741_824, 2),
        cards=cards_html,
        platform_cards=platform_cards_html,
    )

    index = output_dir / "index.html"
    index.write_text(html, encoding="utf-8")
    return index


def generate_site(
    scan_records: list[dict],
    output_dir: str | Path,
    *,
    site_name: str = "My Portfolio",
    photographer: str = "Photographer",
    location: str = "Japan",
    tagline: str = "写真でひとの心を動かす。",
    contact_email: str = "contact@example.com",
    title_tag: str | None = None,
    description: str = "",
    keywords: str = "",
    generate_privacy: bool = True,
    thumb_dir: str | Path | None = None,
) -> dict[str, Path]:
    """
    スキャン結果から完全なマルチページポートフォリオサイトを生成する。

    生成されるファイル:
        output_dir/
        ├── index.html          トップページ（ヒーロー・各セクション・コンタクトフォーム）
        ├── portfolio.html      ポートフォリオ一覧（2列グリッド・モバイル対応）
        ├── works/
        │   └── index.html      ワークス一覧（カテゴリフィルター付き）
        ├── privacy.html        プライバシーポリシー（generate_privacy=True の場合）
        └── thumbs/             サムネイル画像

    Args:
        scan_records:     scanner.scan_to_json() の結果リスト
        output_dir:       サイトの出力先ディレクトリ
        site_name:        サイト名（ナビ・フッターに表示）
        photographer:     撮影者名
        location:         活動拠点
        tagline:          ヒーローセクションのキャッチコピー
        contact_email:    コンタクト用メールアドレス（プライバシーポリシーにも記載）
        title_tag:        SEOタイトルタグ（省略時は site_name を使用）
        description:      SEO メタディスクリプション
        keywords:         SEO キーワード（カンマ区切り）
        generate_privacy: True の場合 privacy.html を生成する
        thumb_dir:        サムネイル画像ディレクトリ

    Returns:
        生成したファイルパスの dict {"index": Path, "portfolio": Path, ...}
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    works_dir = output_dir / "works"
    works_dir.mkdir(exist_ok=True)

    if title_tag is None:
        title_tag = site_name
    if not description:
        description = f"{photographer} — {location}を拠点に活動するフォトグラファー。{tagline}"
    if not keywords:
        keywords = f"{photographer}, フォトグラファー, 写真家, {location}, photography"

    # サムネイルをコピー
    thumb_names: list[str] = []
    if thumb_dir:
        thumb_dir = Path(thumb_dir)
        thumbs_out = output_dir / "thumbs"
        thumbs_out.mkdir(exist_ok=True)
        for img in sorted(thumb_dir.glob("*.jpg")):
            shutil.copy2(img, thumbs_out / img.name)
            thumb_names.append(img.name)

    generated: dict[str, Path] = {}

    # index.html
    index_html = _build_index(
        site_name=site_name,
        photographer=photographer,
        location=location,
        tagline=tagline,
        contact_email=contact_email,
        title_tag=title_tag,
        description=description,
        keywords=keywords,
        thumb_paths=thumb_names,
        scan_records=scan_records,
    )
    index_path = output_dir / "index.html"
    index_path.write_text(index_html, encoding="utf-8")
    generated["index"] = index_path

    # portfolio.html
    portfolio_html = _build_portfolio_page(
        site_name=site_name,
        photographer=photographer,
        title_tag=f"ポートフォリオ | {site_name}",
        description=f"{photographer}の作品一覧です。",
        keywords=keywords,
        thumb_paths=thumb_names,
        scan_records=scan_records,
    )
    portfolio_path = output_dir / "portfolio.html"
    portfolio_path.write_text(portfolio_html, encoding="utf-8")
    generated["portfolio"] = portfolio_path

    # works/index.html
    works_html = _build_works_page(
        site_name=site_name,
        title_tag=f"制作実績 | {site_name}",
        description=f"{photographer}の制作実績一覧です。",
        keywords=keywords,
        scan_records=scan_records,
    )
    works_path = works_dir / "index.html"
    works_path.write_text(works_html, encoding="utf-8")
    generated["works"] = works_path

    # privacy.html
    if generate_privacy:
        privacy_html = _build_privacy_page(
            site_name=site_name,
            photographer=photographer,
            contact_email=contact_email,
            title_tag=title_tag,
        )
        privacy_path = output_dir / "privacy.html"
        privacy_path.write_text(privacy_html, encoding="utf-8")
        generated["privacy"] = privacy_path

    return generated
